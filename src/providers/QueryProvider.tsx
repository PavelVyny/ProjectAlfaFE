'use client';
// =============================================================================
// QueryProvider — обёртка TanStack Query для всего приложения
// =============================================================================
// "use client" обязателен — React хуки (useState) работают только в клиентских
// компонентах. Без этой директивы Next.js пытается рендерить на сервере и падает.
// =============================================================================

import { useState } from 'react';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';

export function QueryProvider({ children }: { children: React.ReactNode }) {
  // ===========================================================================
  // ПОЧЕМУ useState, а не просто const queryClient = new QueryClient()?
  // ===========================================================================
  // В Next.js App Router один модуль может выполниться на сервере ДЛЯ МНОГИХ
  // юзеров одновременно. Если создать QueryClient на уровне модуля:
  //
  //   const queryClient = new QueryClient(); // ← ПЛОХО! Один на всех!
  //
  // ...то ВСЕ серверные рендеры будут шарить один кеш → данные одного юзера
  // утекают другому (security issue).
  //
  // useState(() => new QueryClient()) создаёт НОВЫЙ экземпляр для каждого
  // дерева компонентов. На клиенте это всегда один (браузер = один юзер).
  // На сервере каждый запрос получает свой изолированный кеш.
  // ===========================================================================
  const [queryClient] = useState(
    () =>
      new QueryClient({
        defaultOptions: {
          queries: {
            // staleTime: 60 секунд.
            // "Считай данные свежими 60 сек после получения."
            //
            // Эффект:
            // - Юзер перешёл на другую страницу и вернулся за 30 сек → данные из кеша,
            //   НОЛЬ запросов к серверу
            // - Юзер вернулся через 2 мин → TQ мгновенно показывает кеш (не ждёт!),
            //   но ОДНОВРЕМЕННО делает фоновый запрос (background refetch).
            //   Если данные изменились — UI тихо обновится.
            //
            // Без staleTime (по умолчанию 0): каждый mount компонента = запрос к серверу.
            // Это расточительно — представь 10 компонентов на странице, каждый вызывает
            // useEvents(). С staleTime=0 это 10 одинаковых запросов. С 60s — один.
            staleTime: 60 * 1000,
          },
        },
      }),
  );

  // QueryClientProvider — делает queryClient доступным для всех useQuery/useMutation
  // ниже по дереву через React Context. Без него хуки TQ не работают.
  return (
    <QueryClientProvider client={queryClient}>{children}</QueryClientProvider>
  );
}
